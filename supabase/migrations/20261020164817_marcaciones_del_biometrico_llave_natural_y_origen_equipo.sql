    SELECT 1 FROM pg_class WHERE relname = 'biometrico_marcaciones_respaldo_20261020'
  ) THEN
    EXECUTE 'CREATE TABLE biometrico_marcaciones_respaldo_20261020 AS
             SELECT * FROM biometrico_marcaciones';
  END IF;
