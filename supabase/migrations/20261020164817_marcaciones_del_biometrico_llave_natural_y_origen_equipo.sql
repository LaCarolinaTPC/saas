-- Marcaciones del biométrico: llave natural (device_sn, pin, momento) y vía «equipo»
--
-- Contexto: hasta hoy la llave era `acc_monitor_log.id` (`id_zk`). Eso rompe por
-- dos lados, y los dos son del origen:
--
--   1. El agente pasa a leer las huellas DIRECTO del lector por el SDK de ZK,
--      porque `acc_monitor_log` solo crece cuando alguien abre ZKAccess y
--      descarga a mano. En el lector ese id no existe.
--   2. `acc_monitor_log.id` identifica una FILA DE ZKACCESS, no una huella. El
--      mismo lector (SN AHID222860036) está registrado cuatro veces en la
--      historia de ZKAccess —`device_id` 4, 5, 6 y 7: «Entrada Principal»,
--      «192.168.0.253», «Entrada», «Entrada»— y cada re-registro volvió a
--      descargar su memoria completa. Medido contra producción el 2026-10-20:
--      216.513 filas y solo **158.936 huellas distintas**, o sea **57.577 de
--      más** (249 en 2022, 52.386 en 2023, 4.942 en 2024, ninguna desde 2025).
--      Las 57.577 son estables: el total crece cada día pero los duplicados no.
--
-- La identidad real de una huella es **(equipo, pin, momento)**. Por SN y no por
-- `device_id`, que es justamente lo que cambió en cada re-registro.
--
-- Qué hace, en orden:
--   0. respaldo de la tabla (una sola vez; se borra con una migración posterior)
--   1. device_sn NOT NULL, deducido del device_id en las filas que no lo traen
--   2. columna `id` (IDENTITY) que pasa a ser la PK
--   3. depuración: de cada (device_sn, pin, momento) queda la de MENOR id_zk
--   4. PK a `id`; `id_zk` nulable con UNIQUE parcial
--   5. UNIQUE de la llave natural, `origen`, `recibido_at`, índices
--   6. biometrico_envios: `origen` y `completadas`
--   7. función de ingesta con la fusión entre las dos vías
--   8. función «hasta dónde llegó cada lector»
--   9. comentarios, permisos y comprobación
--
-- Se aplica a mano en el SQL Editor. Tarda segundos (215 k filas) y va en una
-- transacción: o queda todo o no queda nada. Se puede correr entero más de una
-- vez.
--
-- ANTES de aplicarla, correr el ensayo en seco del final del archivo. No se
-- comprueba contra un número fijo (el total crece cada día), sino contra dos
-- invariantes: que borre 57.577 y que la normalización del SN no parta ningún
-- grupo. Si cualquiera falla, PARAR.

