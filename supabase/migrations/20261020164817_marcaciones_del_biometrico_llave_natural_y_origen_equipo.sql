COMMENT ON COLUMN biometrico_marcaciones.id IS
  'PK sustituta, para que el Data API y el catálogo MCP puedan direccionar la fila. La identidad real de una huella es (device_sn, pin, momento).';
COMMENT ON COLUMN biometrico_marcaciones.id_zk IS
  'acc_monitor_log.id cuando la huella llegó (o se completó) por el Access.mdb. NULL mientras solo la haya traído el lector. Es la marca de avance de la vía Access. NO sirve para contar: el mismo lector se registró cuatro veces en ZKAccess y un mismo evento llegó a tener hasta cuatro id_zk.';
COMMENT ON COLUMN biometrico_marcaciones.device_sn IS
  'Número de serie del lector. Parte de la llave natural, así que nunca NULL; en las filas que no lo traían se dedujo del device_id (4,5,6,7 = AHID222860036; 3 = AHID211660104).';
COMMENT ON COLUMN biometrico_marcaciones.origen IS
  'Quién trajo la huella PRIMERO: «equipo» (el agente leyó el lector por el SDK) o «access» (descarga del Access.mdb). No cambia después: una fila del equipo conserva origen=equipo aunque luego Access le complete el id_zk.';
COMMENT ON COLUMN biometrico_marcaciones.recibido_at IS
  'Hora del PC del agente al captar el evento del lector. NULL en la vía Access. Contra `momento` da la latencia real y el desfase del reloj del lector.';
COMMENT ON COLUMN biometrico_marcaciones.verificado IS
  'Vía Access: acc_monitor_log.verified (6 = huella). Vía equipo: traducido del VerifyMethod del SDK; cuando Access completa la fila se sobrescribe con el suyo.';
COMMENT ON FUNCTION biometrico_ingresar_marcaciones(JSONB, UUID) IS
  'Ingresa un lote fusionando las dos vías por (device_sn, pin, momento). Devuelve cuántas se insertaron y a cuántas existentes se les completó el id_zk.';
COMMENT ON FUNCTION biometrico_ultimo_momento_por_equipo() IS
  'Última huella guardada por número de serie de lector. El agente la usa para ponerse al día al reconectarse sin releer toda la memoria del equipo.';

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE biometrico_marcaciones TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE biometrico_envios      TO service_role;
GRANT EXECUTE ON FUNCTION biometrico_ingresar_marcaciones(JSONB, UUID)  TO service_role;
GRANT EXECUTE ON FUNCTION biometrico_ultimo_momento_por_equipo()        TO service_role;

