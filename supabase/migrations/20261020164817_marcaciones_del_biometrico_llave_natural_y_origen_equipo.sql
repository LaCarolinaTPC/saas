-- =============================================================================
-- 3. Depuración: una fila por huella
-- =============================================================================
-- Queda la de MENOR id_zk: es la que ZKAccess descargó primero, y la misma que
-- elige `fusionarPorClave` en el servidor, así que el histórico y los lotes
-- nuevos coinciden. Se agrupa por device_sn a propósito: dos lectores distintos
-- con el mismo pin y el mismo segundo serían dos huellas de verdad.
DELETE FROM biometrico_marcaciones m
 USING (
   SELECT id,
          row_number() OVER (
            PARTITION BY device_sn, pin, momento
            ORDER BY id_zk NULLS LAST, id
          ) AS n
     FROM biometrico_marcaciones
 ) d
 WHERE d.n > 1
   AND m.id = d.id;

