BEGIN
  s := pg_get_serial_sequence('biometrico_marcaciones', 'id');
  IF s IS NOT NULL THEN
    EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO service_role', s);
  END IF;
END $$;

