-- =============================================================================
-- 7. Ingesta: la fusión entre las dos vías
-- =============================================================================
-- No puede ser un upsert de PostgREST: este solo sabe hacer
-- `DO UPDATE SET col = EXCLUDED.col` para TODAS las columnas del payload, y
-- aquí hace falta «rellena id_zk solo si estaba vacío y no pises la cédula».
--
-- Reglas:
--   · fila nueva                              -> se inserta con la cédula que hoy tenga el pin
--   · ya existía y la que llega trae id_zk    -> se le completa id_zk y se toman
--     (vía Access)                               verificado/punto/device_* de Access, que es la
--                                                fuente autoritativa; la cédula solo si estaba
--                                                vacía; `origen` y `envio_id` se conservan
--   · ya existía y la que llega NO trae id_zk -> no se toca
--     (vía equipo)
--
-- El DISTINCT ON evita «ON CONFLICT DO UPDATE command cannot affect row a
-- second time» cuando el lote trae la misma huella dos veces, que es lo normal
-- en la vía Access de 2022-2024.
CREATE OR REPLACE FUNCTION biometrico_ingresar_marcaciones(p_filas JSONB, p_envio_id UUID)
RETURNS TABLE (nuevas INTEGER, completadas INTEGER)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  WITH entrada AS (
    SELECT DISTINCT ON (COALESCE(x.device_sn, ''), x.pin, x.momento)
           x.id_zk,
           x.pin,
           x.momento,
           x.fecha,
           x.device_id,
           x.device_name,
           COALESCE(x.device_sn, '') AS device_sn,
           x.verificado,
           x.punto,
           COALESCE(x.origen, 'access') AS origen,
           x.recibido_at
      FROM jsonb_to_recordset(p_filas) AS x(
             id_zk       BIGINT,
             pin         TEXT,
             momento     TIMESTAMPTZ,
             fecha       DATE,
             device_id   INTEGER,
             device_name TEXT,
             device_sn   TEXT,
             verificado  INTEGER,
             punto       TEXT,
             origen      TEXT,
             recibido_at TIMESTAMPTZ)
     ORDER BY COALESCE(x.device_sn, ''), x.pin, x.momento, x.id_zk NULLS LAST
  ), ins AS (
    INSERT INTO biometrico_marcaciones
           (id_zk, pin, momento, fecha, device_id, device_name, device_sn,
            verificado, punto, cedula, envio_id, origen, recibido_at)
    SELECT e.id_zk, e.pin, e.momento, e.fecha, e.device_id, e.device_name, e.device_sn,
           e.verificado, e.punto, p.cedula, p_envio_id, e.origen, e.recibido_at
      FROM entrada e
      LEFT JOIN biometrico_personas p ON p.pin = e.pin
    ON CONFLICT (device_sn, pin, momento) DO UPDATE
       SET id_zk       = EXCLUDED.id_zk,
           verificado  = EXCLUDED.verificado,
           punto       = EXCLUDED.punto,
           device_id   = EXCLUDED.device_id,
           device_name = EXCLUDED.device_name,
           cedula      = COALESCE(biometrico_marcaciones.cedula, EXCLUDED.cedula)
     WHERE biometrico_marcaciones.id_zk IS NULL
       AND EXCLUDED.id_zk IS NOT NULL
    RETURNING (xmax = 0) AS insertada
  )
  SELECT count(*) FILTER (WHERE insertada)::int,
         count(*) FILTER (WHERE NOT insertada)::int
    FROM ins;
END;
$$;

-- =============================================================================
-- 8. Hasta dónde llegó cada lector
-- =============================================================================
-- El agente la usa al (re)conectarse a un lector para pedirle solo lo que pasó
-- desde entonces. Por SN y no por device_id: el id cambia cada vez que alguien
-- vuelve a registrar el mismo equipo en ZKAccess.
CREATE OR REPLACE FUNCTION biometrico_ultimo_momento_por_equipo()
RETURNS TABLE (device_sn TEXT, momento TIMESTAMPTZ)
LANGUAGE sql
STABLE
AS $$
  SELECT m.device_sn, max(m.momento)
    FROM biometrico_marcaciones m
   WHERE m.device_sn <> ''
   GROUP BY m.device_sn;
$$;

