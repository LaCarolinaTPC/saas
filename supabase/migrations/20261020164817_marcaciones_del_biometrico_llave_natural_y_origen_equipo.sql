       has_function_privilege('service_role', 'biometrico_ultimo_momento_por_equipo()', 'EXECUTE')::text
UNION ALL
SELECT 'por origen', (SELECT string_agg(origen || '=' || n, ' ')
                        FROM (SELECT origen, count(*) n FROM biometrico_marcaciones GROUP BY origen) t)
UNION ALL
SELECT 'por lector', (SELECT string_agg(device_sn || '=' || n, ' ')
                        FROM (SELECT device_sn, count(*) n FROM biometrico_marcaciones GROUP BY device_sn) t);

