-- =============================================================================
-- 1. device_sn: parte de la llave, así que nunca NULL ni vacío si se puede saber
-- =============================================================================
-- Con NULL dos filas idénticas nunca «chocarían» (NULL <> NULL) y se
-- duplicarían. Y 178 huellas vienen sin SN, de las cuales 107 son gemelas de
-- una fila que SÍ lo trae: dejarlas en cadena vacía partiría esos grupos. El
-- `device_id` dice de qué lector son, medido en el .mdb.
UPDATE biometrico_marcaciones
   SET device_sn = CASE
                     WHEN device_id IN (4, 5, 6, 7) THEN 'AHID222860036'
                     WHEN device_id = 3             THEN 'AHID211660104'
                     ELSE ''
                   END
 WHERE device_sn IS NULL OR device_sn = '';

